const messages: Messages = navigator.language.toLowerCase().startsWith('fr') ? fr : en;

/** Returns the translated text for the given key; `{name}` placeholders are replaced by the given values. */
export function t(key: keyof Messages, values?: Record<string, string | number>): string {
  let text = messages[key];
  if (values) {
    for (const [name, value] of Object.entries(values)) {
      text = text.replace(`{${name}}`, String(value));
    }
  }
  return text;
}
